def mc(question, options, answer, skill_tags=None, hints=None, difficulty=1):
    return {
        "type": "multiple_choice",
        "question": question,
        "content": {"options": options},
        "correct_answer": {"answer": answer},
        "skill_tags": skill_tags,
        "hints": hints,
        "difficulty": difficulty,
    }


def terminal(question, answer, skill_tags=None, hints=None, difficulty=1):
    return {
        "type": "terminal",
        "question": question,
        "content": {},
        "correct_answer": {"answer": answer},
        "skill_tags": skill_tags,
        "hints": hints,
        "difficulty": difficulty,
    }


def theory(explanation, example=None, skill_tags=None):
    """Шаг LEARN — объясняет команды/понятия до того, как их спросят, а не после."""
